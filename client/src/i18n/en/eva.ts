export function evaText(key: string, params?: Record<string, string | number>): string {
  let value = en[key] ?? en['eva.unknown_radio']!;
  if (params)
    for (const [name, v] of Object.entries(params))
      value = value.replaceAll(`{${name}}`, String(v));
  return value;
}
